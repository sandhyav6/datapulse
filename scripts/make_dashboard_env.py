"""Write dashboard/.env from the deployed stack's outputs.

Reads the stack with your deploy profile (etl-dev); the dashboard itself then runs as the
read-only etl-dashboard profile.

  python scripts/make_dashboard_env.py
  python scripts/make_dashboard_env.py --dashboard-profile etl-dashboard
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _stack import add_common_args, session, stack_outputs  # noqa: E402

ENV_PATH = Path(__file__).resolve().parent.parent / "dashboard" / ".env"


def render(outputs: dict[str, str], dashboard_profile: str, region: str) -> str:
    lines = [
        "# Generated by scripts/make_dashboard_env.py - do not commit (.env is gitignored)",
        f"AWS_PROFILE={dashboard_profile}",
        f"AWS_REGION={region}",
        f"BUCKET_NAME={outputs['BucketName']}",
        f"TABLE_NAME={outputs['TableName']}",
        f"QUEUE_URL={outputs['QueueUrl']}",
        f"DLQ_URL={outputs['DlqUrl']}",
        f"LOG_GROUP={outputs.get('LogGroupName', '')}",
        f"ATHENA_WORKGROUP={outputs.get('AthenaWorkgroupName', '')}",
        f"GLUE_DATABASE={outputs.get('GlueDatabaseName', '')}",
        "DISPLAY_TZ=Asia/Kolkata",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dashboard-profile", default="etl-dashboard")
    add_common_args(parser)
    args = parser.parse_args()
    outputs = stack_outputs(session(args), args.stack)
    ENV_PATH.write_text(render(outputs, args.dashboard_profile, args.region), encoding="utf-8")
    print(f"Wrote {ENV_PATH}")
    print(f"Dashboard policy to attach to the {args.dashboard_profile} user: "
          f"{outputs.get('DashboardPolicyArn')}")


if __name__ == "__main__":
    main()
